#!/usr/bin/env node
// Copies the dataset out of the evaluation repository so this site cannot drift from it.
// The dataset is the only source of published numbers; nothing here is typed by hand.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = process.env.BENCH_DATASET ?? "D:/Test/data/benchmarks.json";
const DEST = join(HERE, "..", "data", "benchmarks.json");

mkdirSync(dirname(DEST), { recursive: true });
copyFileSync(SRC, DEST);

const d = JSON.parse(readFileSync(DEST, "utf8"));
// The harness dataset records the machine it was built on; a published site should not carry that path.
if (d.meta && d.meta.source_root) delete d.meta.source_root;
writeFileSync(DEST, JSON.stringify(d) + "\n");
const runs = d.meta.runs.length;
const assertions = d.full_benchmark.reduce((a, r) => a + r.checks_total, 0);
writeFileSync(
  join(HERE, "..", "data", "provenance.json"),
  JSON.stringify({
    source: "data/benchmarks.json, generated by the evaluation harness repository",
    models: d.meta.models_with_recorded_results,
    runs,
    modelRuns: d.full_benchmark.length,
    assertions,
    passed: d.full_benchmark.reduce((a, r) => a + r.checks_passed, 0),
    categories: d.meta.categories_scored,
  }, null, 1) + "\n"
);
console.log(`synced ${SRC} -> ${DEST}: ${d.meta.models_with_recorded_results} models, ` +
  `${runs} runs, ${assertions.toLocaleString("en-US")} assertions`);
